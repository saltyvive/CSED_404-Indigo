import Foundation

@main
struct EdgeLiveModelTests {
    static func main() throws {
        let modelURL = URL(fileURLWithPath: CommandLine.arguments[1])
        let model = try JSONDecoder().decode(EdgeLiveModel.self, from: Data(contentsOf: modelURL))
        precondition(model.isValid && Set(model.curves.map(\.edge)) == [.top, .bottom, .left, .right])
        let projector = EdgeProjector(model: model)!
        for curve in model.curves {
            for i in 0...4 {
                precondition(zip(curve.field(at: Double(i)/4), curve.fieldsUT[i]).allSatisfy { abs($0 - $1) < 1e-9 })
                let p = projector.project(curve.fieldsUT[i])!
                precondition(p.accepted && p.edge == curve.edge && abs(p.parameter - Double(i)/4) < 1e-9)
                let expectedPoint = curve.edge.point(Double(i)/4)
                precondition(abs(p.point.x - expectedPoint.x) < 1e-9 && abs(p.point.y - expectedPoint.y) < 1e-9)
                precondition(p.otherEdge != p.edge && p.otherEdgeResidual! >= p.residual)
            }
        }
        // Expected off-knot field values independently generated by Python PCHIP.
        let fixture = try JSONSerialization.jsonObject(with: Data(contentsOf: URL(fileURLWithPath: CommandLine.arguments[2]))) as! [[String: Any]]
        for row in fixture {
            let edge = StudyEdge(rawValue: row["edge"] as! String)!
            let curve = model.curves.first { $0.edge == edge }!
            let s = row["s"] as! Double
            let field = row["field"] as! [Double]
            precondition(zip(curve.field(at: s), field).allSatisfy { abs($0 - $1) < 1e-8 })
            let p = projector.project(field)!
            precondition(p.accepted && p.edge == edge && abs(p.parameter - s) <= 0.0026)
        }
        let noPen = projector.project([0,0,0])!
        precondition(!noPen.accepted && !noPen.showCandidate)
        let mismatch = projector.project([500,500,500])!
        precondition(!mismatch.accepted && mismatch.showCandidate)
        precondition(projector.project([Double.nan, 0, 0]) == nil && projector.project([0]) == nil)
        var bad = model
        bad.curves[0].knots[2] = bad.curves[0].knots[1]
        precondition(!bad.isValid && EdgeProjector(model: bad) == nil)
        bad = model; bad.curves[0].fieldsUT[0] = [1,2]
        precondition(!bad.isValid)
        // Two physically different edges with identical fields are ambiguous.
        let curve = model.curves[0]
        var duplicate = curve; duplicate.edge = .bottom
        var ambiguousModel = model; ambiguousModel.curves = [curve, duplicate]
        let ambiguous = EdgeProjector(model: ambiguousModel)!.project(curve.field(at: 0.5))!
        precondition(ambiguous.ambiguous && !ambiguous.accepted)
        precondition(ambiguous.otherEdgeResidual! < 1e-8)
        // A single-edge model remains readable and has no competing edge.
        var single = model; single.curves = [curve]
        precondition(EdgeProjector(model: single)!.project(curve.field(at: 0.5))!.otherEdge == nil)
        // Alternating edges must use the current sensor field, not a sticky mode.
        for edge in [StudyEdge.bottom, .right, .left, .top, .right, .left, .bottom, .top] {
            let curve = model.curves.first { $0.edge == edge }!
            precondition(projector.project(curve.field(at: 0.625))!.edge == edge)
        }
        // Two adjacent edges may agree at the SAME physical corner. Keep that
        // location visible instead of treating the edge-name tie as ambiguity.
        let sharedTop = EdgeFieldCurve(edge: .top, knots: [0,1], fieldsUT: [[20,20,20],[50,20,20]],
                                       slopesUT: [[30,0,0],[30,0,0]], residualLimitUT: 2,
                                       sourceSession: "synthetic", trainingTrialIDs: [])
        let sharedLeft = EdgeFieldCurve(edge: .left, knots: [0,1], fieldsUT: [[20,20,20],[20,50,20]],
                                        slopesUT: [[0,30,0],[0,30,0]], residualLimitUT: 2,
                                        sourceSession: "synthetic", trainingTrialIDs: [])
        var sharedModel = model; sharedModel.curves = [sharedTop, sharedLeft]
        let corner = EdgeProjector(model: sharedModel)!.project([20,20,20])!
        precondition(corner.accepted && !corner.ambiguous && corner.point.x == 0 && corner.point.y == 0)
        precondition(corner.otherEdgeResidual == 0)
        print("Edge live model tests passed: four edges, vertical coordinates, Python parity, switching, shared corners, ambiguity, invalid input")
    }
}
